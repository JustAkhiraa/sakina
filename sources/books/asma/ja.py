def main():
    base = json.loads(BASE.read_text(encoding="utf-8"))
    manque = [x["n"] for x in base["names"] if x["n"] not in JA]
    if manque:
        print(f"sans traduction : {manque}")

    base["title"] = TITRE
    for x in base["names"]:
        n = x["n"]
        if n in JA:
            x["fr"], x["desc"] = JA[n]
        if n in ASK:
            x["ask"] = ASK[n]

    if "--write" in sys.argv:
        CIBLE.write_text(json.dumps(base, ensure_ascii=False, indent=1) + "\n",
                         encoding="utf-8")
        print(f"content/books/asma.ja.json — {len(JA)} Nom(s), "
              f"{len(ASK)} série(s) de questions")
    else:
        print(f"{len(JA)}/{len(base['names'])} Noms traduits · "
              f"{len(ASK)} série(s) de questions\n\nrelancer avec --write")
    return 0


if __name__ == "__main__":
    sys.exit(main())
